# 01 : return length of the string   {     len()    }
name = "anand"

print(len(name))

# 02 : check wether the  string ends with given string    {     endswith()     }

a = name.endswith ("nd")

print (a)

# 03 : count to total occurrences of a character    {     count()     }

count = name.count("a")
print(count)

# 04 : capatalize the first character        {    capitalized()     }

cap = name.capitalize()
print (cap)

# 05 : return the index of first occurrence   {    find()    }

find = name.find("nd")
print (find)

# 06 : replace the old word with the new word with the string   {   replace("old word", "new word")    }

replace = name.replace("n","a")
print(replace)




